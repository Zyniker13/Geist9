#!/usr/bin/env python3
"""Generates Sources/MailMIME/CharsetTables.swift.

Linux corelibs-foundation ships a trimmed ICU that lacks the "macintosh"
and "euc-jp" converters (and MacRoman's builtin CF converter is compiled
only for Apple platforms), so String(data:encoding:) returns nil for
those two charsets there. To keep decoding deterministic on every
platform, both are decoded from generated tables instead of Foundation:

  - macRomanHigh: the 128 high bytes of Mac OS Roman, from the Unicode
    Consortium mapping (via CPython's mac_roman codec);
  - eucJpPlane1 / eucJpPlane2: the 94x94 JIS X 0208 and JIS X 0212 grids
    (via CPython's euc_jp codec). 0xFFFF marks an undefined slot, which
    decodes as U+FFFD.

Regenerate with: python3 scripts/gen-charset-tables.py
Run from the repository root. Requires CPython 3 (standard codecs only).
"""

import sys

OUT = "Sources/MailMIME/CharsetTables.swift"


def mac_roman_high():
    table = []
    for b in range(0x80, 0x100):
        ch = bytes([b]).decode("mac_roman")
        v = ord(ch)
        assert 0x20 <= v <= 0x10FFFF, hex(b)
        assert not (0xD800 <= v <= 0xDFFF), hex(b)
        table.append(v)
    # ASCII range must be identity.
    for b in range(0x00, 0x80):
        assert bytes([b]).decode("mac_roman") == chr(b)
    return table


def euc_plane(prefix_bytes, name):
    """Decodes one EUC-JP 94x94 plane; returns [(index, value)] for defined slots."""
    defined = {}
    for b1 in range(0xA1, 0xFF):
        for b2 in range(0xA1, 0xFF):
            try:
                ch = (bytes(prefix_bytes) + bytes([b1, b2])).decode("euc_jp")
            except UnicodeDecodeError:
                continue
            v = ord(ch)
            assert not (0xD800 <= v <= 0xDFFF), (name, hex(b1), hex(b2))
            defined[(b1 - 0xA1) * 94 + (b2 - 0xA1)] = v
    return defined


def emit_plane(lines, defined, comment):
    lines.append(f"    /// {comment}")
    lines.append("    static let %s: [UInt16] = [" % ("eucJpPlane1" if "plane 1" in comment else "eucJpPlane2"))
    row = []
    for i in range(94 * 94):
        v = defined.get(i, 0xFFFF)
        row.append(f"0x{v:04X}")
        if len(row) == 16:
            lines.append("        " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("        " + ", ".join(row) + ",")
    lines.append("    ]")
    lines.append("")


def main():
    mac = mac_roman_high()
    plane1 = euc_plane([], "plane1")
    plane2 = euc_plane([0x8F], "plane2")

    # Halfwidth katakana (0x8E-prefixed) must be the arithmetic mapping.
    for k in range(0xA1, 0xE0):
        assert bytes([0x8E, k]).decode("euc_jp") == chr(0xFF61 + k - 0xA1)

    # ASCII range must be identity.
    for b in range(0x00, 0x80):
        assert bytes([b]).decode("euc_jp") == chr(b)

    lines = []
    lines.append("// GENERATED by scripts/gen-charset-tables.py from the Unicode Consortium")
    lines.append("// mappings (via CPython's mac_roman and euc_jp codecs). Do not edit;")
    lines.append("// regenerate with: python3 scripts/gen-charset-tables.py")
    lines.append("//")
    lines.append("// Linux corelibs-foundation ships a trimmed ICU without the macintosh")
    lines.append("// and euc-jp converters, so these two charsets decode from tables on")
    lines.append("// every platform (see Charset.swift). 0xFFFF marks an undefined slot;")
    lines.append("// the decoder renders it as U+FFFD.")
    lines.append("")
    lines.append("enum CharsetTables {")
    lines.append("    /// Mac OS Roman high bytes (0x80-0xFF); 0x00-0x7F is ASCII identity.")
    lines.append(f"    /// Generated: {len(mac)} entries.")
    lines.append("    static let macRomanHigh: [UInt32] = [")
    for i in range(0, len(mac), 8):
        chunk = ", ".join(f"0x{v:04X}" for v in mac[i:i + 8])
        lines.append(f"        {chunk},")
    lines.append("    ]")
    lines.append("")
    emit_plane(lines, plane1, "EUC-JP plane 1: JIS X 0208, two bytes 0xA1-0xFE, row-major 94x94.")
    emit_plane(lines, plane2, "EUC-JP plane 2: JIS X 0212, prefix 0x8F then two bytes 0xA1-0xFE, row-major 94x94.")
    lines.append("}")
    lines.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(lines))

    print(f"wrote {OUT}: macRoman {len(mac)}, plane1 {len(plane1)}/{94*94}, plane2 {len(plane2)}/{94*94}")

    # Print fixture suggestions for the tests: first X0212-only kanji slot.
    for i in sorted(plane2):
        v = plane2[i]
        if 0x4E00 <= v <= 0x9FFF:
            b1, b2 = 0xA1 + i // 94, 0xA1 + i % 94
            print(f"first defined plane2 CJK slot: bytes 8f {b1:02x} {b2:02x} -> U+{v:04X} {chr(v)!r}")
            break
    for i in sorted(plane1):
        v = plane1[i]
        if 0x4E00 <= v <= 0x9FFF:
            b1, b2 = 0xA1 + i // 94, 0xA1 + i % 94
            print(f"first defined plane1 CJK slot: bytes {b1:02x} {b2:02x} -> U+{v:04X} {chr(v)!r}")
            break
    return 0


if __name__ == "__main__":
    sys.exit(main())
